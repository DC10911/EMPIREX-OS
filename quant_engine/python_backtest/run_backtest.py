def load_csv(path: str, symbol: str) -> pd.DataFrame:
    """
    Load OHLCV data from a CSV file.
    Expects columns (case-insensitive): datetime, open, high, low, close[, volume]
    datetime column is parsed as UTC.
    """
    df = pd.read_csv(path)
    df.columns = df.columns.str.lower().str.strip()

    # Find datetime column
    dt_col = None
    for c in ("datetime", "date", "time", "timestamp", "date_time"):
        if c in df.columns:
            dt_col = c
            break
    if dt_col is None:
        raise ValueError(
            f"Cannot find datetime column in {path}. "
            "Expected one of: datetime, date, time, timestamp"
        )

    df[dt_col] = pd.to_datetime(df[dt_col], utc=True)
    df = df.set_index(dt_col)
    df.index.name = "datetime"

    required = {"open", "high", "low", "close"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"CSV missing columns: {missing}")

    if "volume" not in df.columns:
        df["volume"] = 1.0

    df = df[["open", "high", "low", "close", "volume"]].astype(float)
    df.sort_index(inplace=True)
    return df


def load_yfinance(symbol: str, start: str, end: str) -> pd.DataFrame:
    """
    Download 1H OHLCV bars from yfinance.
    Requires: pip install yfinance
    """
    try:
        import yfinance as yf
    except ImportError:
        raise ImportError(
            "yfinance is not installed. Run: pip install yfinance\n"
            "Or supply a CSV file with --data-file."
        )

    TICKER_MAP = {
        "EURUSD": "EURUSD=X",
        "GBPUSD": "GBPUSD=X",
        "XAUUSD": "GC=F",
        "NAS100": "NQ=F",
    }
    ticker = TICKER_MAP.get(symbol.upper())
    if ticker is None:
        raise ValueError(f"No yfinance ticker mapping for symbol: {symbol}")

    print(f"[INFO] Downloading {symbol} ({ticker}) from yfinance ...")
    raw = yf.download(ticker, start=start, end=end, interval="1h", auto_adjust=True, progress=False)
    if raw.empty:
        raise RuntimeError(
            f"yfinance returned no data for {ticker} between {start} and {end}."
        )

    raw.columns = [c.lower() for c in raw.columns]
    # yfinance may return a MultiIndex; flatten if needed
    if isinstance(raw.columns, pd.MultiIndex):
        raw.columns = raw.columns.get_level_values(0)

    if raw.index.tz is None:
        raw.index = raw.index.tz_localize("UTC")
    else:
        raw.index = raw.index.tz_convert("UTC")

    df = raw[["open", "high", "low", "close", "volume"]].copy().astype(float)
    df.sort_index(inplace=True)
    return df


