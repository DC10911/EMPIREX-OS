def _self_test() -> None:
    """
    Quick smoke test — runs both strategies on synthetic data for each
    supported symbol and asserts basic sanity checks.
    Invoked with: python run_backtest.py --self-test
    """
    print("\n[SELF-TEST] Running smoke tests with SYNTHETIC data ...")
    errors = []
    symbols = list(INSTRUMENT_SPECS.keys())
    strategies = [("LRB", LRBStrategy), ("EMP", EMPSessionMomentumStrategy)]

    for sym in symbols:
        df = generate_synthetic_ohlcv(sym, "2026-01-01", "2026-03-31", seed=7)
        for strat_name, StratCls in strategies:
            try:
                engine = BacktestEngine(sym, strat_name, initial_capital=10_000, lot_size=0.1)
                engine.run(df, StratCls())
                res = engine.get_results()
                assert isinstance(res["trades"], pd.DataFrame), "Trades not a DataFrame"
                assert isinstance(res["equity_curve"], pd.Series), "Equity curve not a Series"
                print(f"  [OK] {sym} / {strat_name} — {len(res['trades'])} trades")
            except Exception as e:
                errors.append(f"{sym}/{strat_name}: {e}")
                print(f"  [FAIL] {sym} / {strat_name}: {e}")

    if errors:
        print(f"\n[SELF-TEST] FAILED — {len(errors)} error(s):")
        for e in errors:
            print(f"  {e}")
        sys.exit(1)
    else:
        print("\n[SELF-TEST] All tests passed.")


# ===========================================================================

if __name__ == "__main__":
    # Handle --self-test as a special flag before argparse
    if "--self-test" in sys.argv:
        _self_test()
    else:
        main()
