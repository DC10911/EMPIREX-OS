def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description=(
            "EMPIREX-OS Python Backtesting Framework\n"
            "----------------------------------------\n"
            "Run London Range Breakout (LRB) and EMP Session Momentum strategies.\n\n"
            "WARNING: --demo mode uses SYNTHETIC data. NOT for live trading."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--demo",
        action="store_true",
        help="Run with SYNTHETIC data for demonstration. Labels output [SIMULATED].",
    )
    p.add_argument(
        "--symbol",
        type=str,
        default="EURUSD",
        choices=list(INSTRUMENT_SPECS.keys()),
        help="Instrument to backtest (default: EURUSD)",
    )
    p.add_argument(
        "--strategy",
        type=str,
        default="both",
        choices=["LRB", "EMP", "both"],
        help="Strategy to run: LRB | EMP | both (default: both)",
    )
    p.add_argument(
        "--start",
        type=str,
        default="2026-01-01",
        help="Backtest start date YYYY-MM-DD UTC (default: 2026-01-01)",
    )
    p.add_argument(
        "--end",
        type=str,
        default="2026-06-28",
        help="Backtest end date YYYY-MM-DD UTC (default: 2026-06-28)",
    )
    p.add_argument(
        "--data-file",
        type=str,
        default=None,
        help="Path to CSV file with OHLCV data (overrides yfinance download)",
    )
    p.add_argument(
        "--initial-capital",
        type=float,
        default=10_000.0,
        help="Starting account equity in USD (default: 10000)",
    )
    p.add_argument(
        "--lot-size",
        type=float,
        default=0.1,
        help="Lot size for each trade (default: 0.1)",
    )
    p.add_argument(
        "--output-dir",
        type=str,
        default="./backtest_results",
        help="Directory for CSV export (default: ./backtest_results)",
    )
    p.add_argument(
        "--no-csv",
        action="store_true",
        help="Skip CSV export",
    )
    p.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for --demo synthetic data (default: 42)",
    )
    return p


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    # ---- Print demo warning first ----
    if args.demo:
        print(_DEMO_WARNING)

    start = pd.Timestamp(args.start, tz="UTC")
    end = pd.Timestamp(args.end, tz="UTC")

    if start >= end:
        parser.error("--start must be before --end")

    symbol = args.symbol.upper()
    is_simulated = args.demo

    # ---- Load data ----
    if args.demo:
        print(f"[SIMULATED] Generating synthetic OHLCV data for {symbol} ...")
        df = generate_synthetic_ohlcv(
            symbol=symbol,
            start=args.start,
            end=args.end,
            seed=args.seed,
        )
        print(f"[SIMULATED] Generated {len(df):,} bars from {df.index[0]} to {df.index[-1]}")
    elif args.data_file:
        print(f"[INFO] Loading data from {args.data_file} ...")
        df = load_csv(args.data_file, symbol)
        print(f"[INFO] Loaded {len(df):,} bars from {df.index[0]} to {df.index[-1]}")
    else:
        df = load_yfinance(symbol, args.start, args.end)
        print(f"[INFO] Downloaded {len(df):,} bars from {df.index[0]} to {df.index[-1]}")

    if df.empty:
        print("[ERROR] No data loaded. Exiting.")
        sys.exit(1)

    # ---- Determine strategies to run ----
    strategies_to_run = []
    if args.strategy == "both":
        strategies_to_run = ["LRB", "EMP"]
    else:
        strategies_to_run = [args.strategy]

    # ---- Run strategies ----
    reporters: list[PerformanceReporter] = []
    for strat in strategies_to_run:
        print(f"\n[INFO] Running {strat} strategy on {symbol} ...")
        try:
            reporter = run_strategy(
                symbol=symbol,
                strategy_name=strat,
                df=df,
                start=start,
                end=end,
                initial_capital=args.initial_capital,
                lot_size=args.lot_size,
                is_simulated=is_simulated,
            )
            reporters.append(reporter)
        except Exception as exc:
            print(f"[ERROR] Strategy {strat} failed: {exc}")
            import traceback
            traceback.print_exc()
            continue

    if not reporters:
        print("[ERROR] No strategies completed successfully.")
        sys.exit(1)

    # ---- Print results ----
    if args.demo:
        print("\n" + "!" * 70)
        print("!!! ALL RESULTS BELOW ARE FROM SIMULATED (SYNTHETIC) DATA !!!!")
        print("!!! DO NOT USE THESE NUMBERS FOR LIVE TRADING DECISIONS    !!!!")
        print("!" * 70)

    for r in reporters:
        r.print_all()

    if len(reporters) > 1:
        print_benchmark_comparison(reporters)

    # ---- CSV export ----
    if not args.no_csv:
        output_dir = args.output_dir
        print(f"\n[INFO] Exporting results to {output_dir}/ ...")
        all_files = []
        for r in reporters:
            files = r.export_csv(output_dir)
            all_files.extend(files)

        if len(reporters) > 1:
            cmp_file = export_benchmark_comparison_csv(reporters, output_dir)
            all_files.append(cmp_file)

        for f in all_files:
            print(f"  [CSV] {f}")

    # ---- Final reminder for demo ----
    if args.demo:
        print(_DEMO_WARNING)

    print("\n[INFO] Backtest complete.")


