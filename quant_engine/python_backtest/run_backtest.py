def generate_synthetic_ohlcv(
    symbol: str,
    start: str = "2026-01-01",
    end: str = "2026-06-28",
    seed: int = 42,
) -> pd.DataFrame:
    """
    Generate synthetic 1H OHLCV bars using a geometric random walk.

    THIS DATA IS ENTIRELY FICTIONAL.  It is provided only to demonstrate
    that the framework runs correctly end-to-end.  No inference about real
    markets should be drawn from synthetic results.

    Parameters
    ----------
    symbol : one of EURUSD, GBPUSD, XAUUSD, NAS100
    start / end : date strings (inclusive)
    seed : random seed for reproducibility

    Returns
    -------
    pd.DataFrame with DatetimeIndex (UTC) and columns: open, high, low, close, volume
    """
    rng = np.random.default_rng(seed)

    SEED_PRICES = {
        "EURUSD": 1.05000,
        "GBPUSD": 1.25000,
        "XAUUSD": 2300.00,
        "NAS100": 17500.0,
    }
    VOLATILITY = {           # per-bar log-return std dev (hourly)
        "EURUSD": 0.00030,
        "GBPUSD": 0.00035,
        "XAUUSD": 0.00120,
        "NAS100": 0.00200,
    }
    SPREAD_FACTOR = {
        "EURUSD": 0.00020,
        "GBPUSD": 0.00022,
        "XAUUSD": 0.50,
        "NAS100": 3.0,
    }

    idx = pd.date_range(start=start, end=end, freq="1h", tz="UTC")
    # Remove weekends (FX / index markets mostly closed)
    idx = idx[idx.dayofweek < 5]
    n = len(idx)

    vol = VOLATILITY[symbol]
    price = SEED_PRICES[symbol]
    spread = SPREAD_FACTOR[symbol]

    closes = np.zeros(n)
    opens = np.zeros(n)
    highs = np.zeros(n)
    lows = np.zeros(n)
    volumes = rng.integers(500, 5000, size=n).astype(float)

    cur = price
    for i in range(n):
        # Simulate intrabar behaviour with 4 sub-ticks
        ret = rng.normal(0, vol)
        # Mild mean-reversion to seed price
        ret += (math.log(price) - math.log(cur)) * 0.001
        o = cur
        ticks = [cur * math.exp(rng.normal(0, vol * 0.5)) for _ in range(4)]
        c = cur * math.exp(ret)
        ticks.append(c)
        h = max(max(ticks), o, c) + spread * 0.5
        l = min(min(ticks), o, c) - spread * 0.5
        opens[i] = o
        closes[i] = c
        highs[i] = h
        lows[i] = max(l, c * 0.98)  # floor to avoid negative
        cur = c

    df = pd.DataFrame(
        {"open": opens, "high": highs, "low": lows, "close": closes, "volume": volumes},
        index=idx,
    )
    return df


