def run_strategy(
    symbol: str,
    strategy_name: str,
    df: pd.DataFrame,
    start: pd.Timestamp,
    end: pd.Timestamp,
    initial_capital: float,
    lot_size: float,
    is_simulated: bool,
) -> PerformanceReporter:
    """Run a single strategy on a single symbol and return a reporter."""
    # Filter to requested date range
    df_range = df[(df.index >= start) & (df.index <= end)].copy()

    if df_range.empty:
        print(f"[WARN] No data for {symbol} between {start.date()} and {end.date()}")
        # Return an empty reporter
        empty_results = {
            "symbol": symbol,
            "strategy": strategy_name,
            "initial_capital": initial_capital,
            "final_equity": initial_capital,
            "trades": pd.DataFrame(),
            "equity_curve": pd.Series([initial_capital]),
        }
        return PerformanceReporter(empty_results, start, end, is_simulated)

    if strategy_name == "LRB":
        strategy = LRBStrategy()
    elif strategy_name in ("EMP", "EMPSessionMomentum"):
        strategy = EMPSessionMomentumStrategy()
    else:
        raise ValueError(f"Unknown strategy: {strategy_name}")

    engine = BacktestEngine(
        symbol=symbol,
        strategy_name=strategy_name,
        initial_capital=initial_capital,
        lot_size=lot_size,
    )
    engine.run(df_range, strategy)
    results = engine.get_results()

    return PerformanceReporter(results, start, end, is_simulated)


